package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func write(t *testing.T, dir, name, content string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestCheckTree(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", "package x\n")
	write(t, dir, "long.go", "package x\n// "+strings.Repeat("a", 30)+"\n")
	write(t, dir, "big.go", strings.Repeat("x\n", 6))
	write(t, dir, "big_test.go", strings.Repeat("x\n", 6))
	write(t, dir, "gen.go", "// Code generated by x. DO NOT EDIT.\n"+strings.Repeat("a", 99)+"\n")
	write(t, dir, "notes.txt", strings.Repeat("a", 99)+"\n")
	write(t, dir, "vendor/v.go", strings.Repeat("a", 99)+"\n")

	v, err := CheckTree(dir, Limits{MaxLine: 20, MaxFile: 5, MaxTestFile: 10})
	if err != nil {
		t.Fatal(err)
	}
	if len(v) != 2 {
		t.Fatalf("want 2 violations, got %d: %v", len(v), v)
	}
	got := v[0].String() + "\n" + v[1].String()
	if !strings.Contains(got, "big.go: file has 6 lines") || !strings.Contains(got, "long.go:2: line is") {
		t.Fatalf("unexpected violations: %s", got)
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", "package x\n")
	var buf bytes.Buffer
	if code := run([]string{dir}, &buf); code != 0 {
		t.Fatalf("want 0, got %d: %s", code, buf.String())
	}
	write(t, dir, "bad.go", strings.Repeat("a", 200)+"\n")
	buf.Reset()
	if code := run([]string{dir}, &buf); code != 1 {
		t.Fatalf("want 1, got %d", code)
	}
	if code := run([]string{"-nope"}, &buf); code != 2 {
		t.Fatalf("want 2 for bad flag, got %d", code)
	}
	if code := run([]string{filepath.Join(dir, "missing")}, &buf); code != 2 {
		t.Fatalf("want 2 for missing dir, got %d", code)
	}
}

func TestRunDefaultDir(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", "package x\n")
	wd, _ := os.Getwd()
	t.Cleanup(func() { _ = os.Chdir(wd) })
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	var buf bytes.Buffer
	if code := run(nil, &buf); code != 0 {
		t.Fatalf("want 0, got %d", code)
	}
}

